/**
 * Create the full test schema on the given PDO connection (SQLite).
 * Call this at the top of every DB-dependent test file.
 */
function createTestSchema(PDO $db): void {
    $db->exec("
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            name TEXT NOT NULL,
            email TEXT NOT NULL UNIQUE,
            password TEXT NOT NULL,
            postal_address TEXT NOT NULL,
            accepts_adult_zines INTEGER DEFAULT 0,
            country TEXT NOT NULL,
            is_admin INTEGER DEFAULT 0,
            email_confirmed INTEGER DEFAULT 0,
            email_confirmation_token TEXT,
            email_token_expires TEXT,
            password_reset_token TEXT,
            password_reset_expires TEXT,
            created_at TEXT DEFAULT (datetime('now')),
            updated_at TEXT DEFAULT (datetime('now'))
        )
    ");

    $db->exec("
        CREATE TABLE IF NOT EXISTS zines (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id INTEGER NOT NULL,
            theme TEXT,
            format TEXT,
            created_at TEXT DEFAULT (datetime('now')),
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
        )
    ");

    $db->exec("
        CREATE TABLE IF NOT EXISTS cycles (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            name TEXT NOT NULL,
            start_date TEXT NOT NULL,
            registration_open INTEGER DEFAULT 1,
            pairing_done INTEGER DEFAULT 0,
            status TEXT DEFAULT 'active',
            created_at TEXT DEFAULT (datetime('now'))
        )
    ");

    $db->exec("
        CREATE TABLE IF NOT EXISTS cycle_participations (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            cycle_id INTEGER NOT NULL,
            user_id INTEGER NOT NULL,
            wants_to_participate INTEGER DEFAULT 1,
            participation_confirmed INTEGER DEFAULT 0,
            pairing_confirmed INTEGER DEFAULT 0,
            paired_with_id INTEGER,
            zine_sent INTEGER DEFAULT 0,
            zine_sent_date TEXT,
            zine_received INTEGER DEFAULT 0,
            zine_received_date TEXT,
            confirmation_token TEXT,
            confirmation_token_expires TEXT,
            created_at TEXT DEFAULT (datetime('now')),
            updated_at TEXT DEFAULT (datetime('now')),
            FOREIGN KEY (cycle_id) REFERENCES cycles(id) ON DELETE CASCADE,
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
            FOREIGN KEY (paired_with_id) REFERENCES users(id) ON DELETE SET NULL,
            UNIQUE (cycle_id, user_id)
        )
    ");

    $db->exec("
        CREATE TABLE IF NOT EXISTS cycle_pairings (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            cycle_id INTEGER NOT NULL,
            user_id INTEGER NOT NULL,
            partner_id INTEGER NOT NULL,
            pairing_confirmed INTEGER DEFAULT 0,
            confirmation_token TEXT,
            confirmation_token_expires TEXT,
            zine_sent INTEGER DEFAULT 0,
            zine_sent_date TEXT,
            zine_received INTEGER DEFAULT 0,
            zine_received_date TEXT,
            created_at TEXT DEFAULT (datetime('now')),
            FOREIGN KEY (cycle_id) REFERENCES cycles(id) ON DELETE CASCADE,
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
            FOREIGN KEY (partner_id) REFERENCES users(id) ON DELETE CASCADE
        )
    ");

    $db->exec("
        CREATE TABLE IF NOT EXISTS email_logs (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id INTEGER,
            cycle_id INTEGER,
            email_type TEXT NOT NULL,
            sent_at TEXT DEFAULT (datetime('now')),
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
            FOREIGN KEY (cycle_id) REFERENCES cycles(id) ON DELETE SET NULL
        )
    ");

    $db->exec("
        CREATE TABLE IF NOT EXISTS announcements (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            title TEXT NOT NULL,
            content TEXT NOT NULL,
            created_at TEXT DEFAULT (datetime('now')),
            updated_at TEXT DEFAULT (datetime('now')),
            created_by INTEGER NOT NULL,
            email_sent INTEGER DEFAULT 0,
            FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE CASCADE
        )
    ");

    $db->exec("
        CREATE TABLE IF NOT EXISTS announcement_views (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            announcement_id INTEGER NOT NULL,
            user_id INTEGER NOT NULL,
            viewed_at TEXT DEFAULT (datetime('now')),
            UNIQUE (announcement_id, user_id),
            FOREIGN KEY (announcement_id) REFERENCES announcements(id) ON DELETE CASCADE,
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
        )
    ");
}

