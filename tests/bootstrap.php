/**
 * Insert a test user and return its ID.
 */
function insertTestUser(PDO $db, array $overrides = []): int {
    $defaults = [
        'name'                => 'Test User',
        'email'               => 'test@example.com',
        'password'            => password_hash('secret123', PASSWORD_DEFAULT),
        'postal_address'      => '123 Test St',
        'country'             => 'US',
        'accepts_adult_zines' => 0,
        'is_admin'            => 0,
        'email_confirmed'     => 1,
    ];
    $data = array_merge($defaults, $overrides);

    // Only pass columns that exist in the INSERT query
    $columns = ['name', 'email', 'password', 'postal_address', 'country',
                'accepts_adult_zines', 'is_admin', 'email_confirmed'];
    $filtered = array_intersect_key($data, array_flip($columns));

    $stmt = $db->prepare("
        INSERT INTO users (name, email, password, postal_address, country,
                           accepts_adult_zines, is_admin, email_confirmed)
        VALUES (:name, :email, :password, :postal_address, :country,
                :accepts_adult_zines, :is_admin, :email_confirmed)
    ");
    $stmt->execute($filtered);
    return (int)$db->lastInsertId();
}

