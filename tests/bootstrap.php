// ── Assertion helpers ───────────────────────────────────────────────

function assert_equal(string $label, mixed $expected, mixed $actual): void {
    if ($expected === $actual) {
        echo "[PASS] {$label}\n";
    } else {
        $exp = var_export($expected, true);
        $got = var_export($actual, true);
        echo "[FAIL] {$label} -- expected {$exp} got {$got}\n";
    }
}

function assert_true(string $label, bool $result): void {
    echo ($result ? "[PASS]" : "[FAIL]") . " {$label}\n";
}

function assert_throws(string $label, callable $fn, string $exceptionClass = \Throwable::class): void {
    try {
        $fn();
        echo "[FAIL] {$label} -- no exception was thrown\n";
    } catch (\Throwable $e) {
        if ($e instanceof $exceptionClass) {
            echo "[PASS] {$label}\n";
        } else {
            echo "[FAIL] {$label} -- expected {$exceptionClass} got " . get_class($e) . "\n";
        }
    }
}

